CREATE TABLE CASH_TRANSACTION ( 
 ID_CASH_TRANSACTION INT PRIMARY KEY AUTO_INCREMENT,  
 ID_SALE INT,  
 TRANSACTION_DATE DATE,  
 TRANSACTION_TYPE VARCHAR (120) NOT NULL,  
 PAYMENT_METHOD VARCHAR (120) NOT NULL,  
 AMOUNT DECIMAL (10,2)
); 
ALTER TABLE CASH_TRANSACTION
ADD CONSTRAINT FK_CASH_TRANSACTION_SALE
FOREIGN KEY (ID_SALE)
REFERENCES SALE (ID_SALE);

INSERT INTO CASH_TRANSACTION
(ID_SALE, TRANSACTION_DATE, TRANSACTION_TYPE, PAYMENT_METHOD, AMOUNT)
SELECT
    S.ID_SALE,
    S.SALE_DATE,
    'ENTRADA',
    'NAO INFORMADO',
    SUM(SI.QUANTITY * SI.UNIT_SELLING_PRICE)
FROM SALE S
INNER JOIN SALE_ITEM SI
    ON S.ID_SALE = SI.ID_SALE
WHERE S.PAYMENT_STATUS = 'PAID'
AND NOT EXISTS (
    SELECT 1
    FROM CASH_TRANSACTION CT
    WHERE CT.ID_SALE = S.ID_SALE
      AND CT.TRANSACTION_TYPE = 'ENTRADA'
)
GROUP BY S.ID_SALE, S.SALE_DATE;
;
